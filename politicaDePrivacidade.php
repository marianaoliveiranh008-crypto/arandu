            <h1 id="politica-titulo">Política de Privacidade - Livraria Arandu</h1>
            <p class="termos-atualizacao">Última atualização: 01 de outubro de 2026</p>

            <div class="termos-conteudo">
                <p>A Livraria Arandu valoriza a privacidade e a segurança dos dados pessoais de seus usuários. Esta Política de Privacidade explica como os dados são coletados, utilizados, armazenados e protegidos durante a utilização do nosso site.</p>

                <section>
                    <h2>1. Quais dados podemos coletar</h2>
                    <p>Dependendo da utilização do site, podemos coletar:</p>

                    <h3>Dados de cadastro</h3>
                    <ul>
                        <li>Nome completo;</li>
                        <li>CPF, quando necessário;</li>
                        <li>E-mail;</li>
                        <li>Telefone;</li>
                        <li>Senha de acesso.</li>
                    </ul>

                    <h3>Dados de entrega</h3>
                    <ul>
                        <li>Endereço;</li>
                        <li>Número;</li>
                        <li>Complemento;</li>
                        <li>Bairro;</li>
                        <li>Cidade;</li>
                        <li>Estado;</li>
                        <li>CEP.</li>
                    </ul>

                    <h3>Dados relacionados às compras</h3>
                    <ul>
                        <li>Produtos adquiridos;</li>
                        <li>Quantidade;</li>
                        <li>Valor do pedido;</li>
                        <li>Histórico de pedidos;</li>
                        <li>Forma de pagamento;</li>
                        <li>Status da compra.</li>
                    </ul>

                    <h3>Dados de navegação</h3>
                    <ul>
                        <li>Endereço IP;</li>
                        <li>Informações sobre o dispositivo e navegador;</li>
                        <li>Data e horário de acesso;</li>
                        <li>Informações relacionadas à utilização do site.</li>
                    </ul>
                </section>

                <section>
                    <h2>2. Para que utilizamos os dados</h2>
                    <p>Os dados pessoais poderão ser utilizados para:</p>
                    <ul>
                        <li>criar e administrar a conta do usuário;</li>
                        <li>processar pedidos;</li>
                        <li>realizar pagamentos;</li>
                        <li>realizar a entrega dos produtos;</li>
                        <li>enviar informações relacionadas aos pedidos;</li>
                        <li>prestar atendimento ao cliente;</li>
                        <li>melhorar o funcionamento do site;</li>
                        <li>prevenir fraudes e usos indevidos;</li>
                        <li>cumprir obrigações legais e regulatórias.</li>
                    </ul>
                    <p>Os dados devem ser utilizados de acordo com as finalidades informadas e de forma compatível com o contexto do tratamento.</p>
                </section>

                <section>
                    <h2>3. Compartilhamento de dados</h2>
                    <p>Quando necessário para a prestação dos serviços, determinados dados poderão ser compartilhados com empresas que auxiliem na operação da Livraria Arandu, como:</p>
                    <ul>
                        <li>empresas de processamento de pagamentos;</li>
                        <li>empresas responsáveis pela entrega dos pedidos;</li>
                        <li>fornecedores de tecnologia e hospedagem;</li>
                        <li>prestadores de serviços necessários ao funcionamento da plataforma.</li>
                    </ul>
                    <p>O compartilhamento será limitado ao necessário para a finalidade correspondente.</p>
                </section>

                <section>
                    <h2>4. Dados de pagamento</h2>
                    <p>Os dados necessários para realizar pagamentos poderão ser processados por provedores especializados.</p>
                    <p>A Livraria Arandu não deverá armazenar informações completas de cartões de pagamento quando isso não for necessário para a prestação do serviço.</p>
                </section>

                <section>
                    <h2>5. Cookies</h2>
                    <p>O site poderá utilizar cookies e tecnologias semelhantes para:</p>
                    <ul>
                        <li>manter o funcionamento da plataforma;</li>
                        <li>lembrar determinadas preferências;</li>
                        <li>compreender como o site é utilizado;</li>
                        <li>melhorar a experiência do usuário;</li>
                        <li>realizar funções de segurança.</li>
                    </ul>
                    <p>Quando aplicável, o usuário poderá gerenciar suas preferências de cookies por meio das configurações disponibilizadas no site.</p>
                </section>

                <section>
                    <h2>6. Segurança dos dados</h2>
                    <p>A Livraria Arandu adotará medidas técnicas e administrativas adequadas para proteger os dados pessoais contra acessos não autorizados, perda, alteração, destruição ou divulgação indevida.</p>
                    <p>Entre as medidas de segurança poderão estar o controle de acesso, uso de senhas, criptografia e mecanismos de proteção da plataforma.</p>
                </section>

                <section>
                    <h2>7. Armazenamento dos dados</h2>
                    <p>Os dados pessoais serão mantidos pelo período necessário para cumprir as finalidades para as quais foram coletados e para atender obrigações legais, regulatórias ou outras hipóteses permitidas pela legislação.</p>
                    <p>Quando não houver mais necessidade de manutenção dos dados, eles poderão ser eliminados ou anonimizados, observadas as hipóteses legais de conservação.</p>
                </section>

                <section>
                    <h2>8. Direitos do usuário</h2>
                    <p>Nos termos da legislação aplicável, especialmente da LGPD, o titular poderá exercer direitos relacionados aos seus dados pessoais, incluindo:</p>
                    <ul>
                        <li>confirmação da existência de tratamento;</li>
                        <li>acesso aos dados;</li>
                        <li>correção de dados incompletos, incorretos ou desatualizados;</li>
                        <li>informações sobre o uso e compartilhamento dos dados;</li>
                        <li>solicitação de anonimização, bloqueio ou eliminação, quando aplicável;</li>
                        <li>revogação do consentimento, quando o tratamento estiver baseado em consentimento;</li>
                        <li>demais direitos previstos na legislação.</li>
                    </ul>
                    <p>A ANPD orienta que o titular solicite inicialmente o exercício de seus direitos diretamente ao controlador responsável pelo tratamento.</p>
                </section>

                <section>
                    <h2>9. Solicitação de direitos</h2>
                    <p>Para solicitar informações, correções ou outras providências relacionadas aos seus dados pessoais, o usuário poderá entrar em contato com a Livraria Arandu por meio do canal de atendimento disponibilizado no site.</p>
                    <p>A solicitação será analisada de acordo com a legislação aplicável.</p>
                </section>

                <section>
                    <h2>10. Proteção de menores</h2>
                    <p>O site não tem como finalidade a coleta intencional de dados de crianças sem as condições e autorizações exigidas pela legislação aplicável.</p>
                </section>

                <section>
                    <h2>11. Alterações desta Política</h2>
                    <p>Esta Política de Privacidade poderá ser atualizada para refletir mudanças no funcionamento do site, nos serviços oferecidos ou na legislação.</p>
                    <p>A versão mais recente ficará disponível no site, acompanhada da respectiva data de atualização.</p>
                </section>

                <section>
                    <h2>12. Contato</h2>
                    <p>Para dúvidas ou solicitações relacionadas à privacidade e ao tratamento de dados pessoais, o usuário poderá utilizar o canal de atendimento disponibilizado pela Livraria Arandu.</p>
                    <p>E-mail: [inserir e-mail oficial]</p>
                    <p>Responsável pelo tratamento de dados/Encarregado: [inserir nome ou canal de contato, conforme aplicável]</p>
                </section>

                <section>
                    <h2>13. Aceitação</h2>
                    <p>Ao utilizar o site, o usuário declara estar ciente desta Política de Privacidade e de que seus dados poderão ser tratados conforme as finalidades e condições aqui descritas.</p>
                </section>
